import { randomBytes } from 'node:crypto';
import { lstat, mkdir, open, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { getConfig, type StorageBackend } from '../config';

export interface AvatarStorage {
  readonly mode: 'real' | 'fake';
  readonly backend: StorageBackend;
  put(objectPath: string, data: Buffer, contentType: string): Promise<void>;
  get(objectPath: string): Promise<{ data: Buffer; contentType: string } | null>;
}

/** Supabase Storage via REST with the server-only service role key (bucket stays private). */
export class SupabaseAvatarStorage implements AvatarStorage {
  readonly mode = 'real' as const;
  readonly backend = 'supabase' as const;
  constructor(private url: string, private key: string, private bucket: string) {}
  async put(objectPath: string, data: Buffer, contentType: string) {
    const res = await fetch(`${this.url}/storage/v1/object/${this.bucket}/${objectPath}`, {
      method: 'POST',
      headers: { authorization: `Bearer ${this.key}`, apikey: this.key, 'content-type': contentType, 'x-upsert': 'true' },
      body: new Uint8Array(data),
      signal: AbortSignal.timeout(15_000),
    });
    if (!res.ok) throw new Error(`storage_put_${res.status}`);
  }
  async get(objectPath: string) {
    const res = await fetch(`${this.url}/storage/v1/object/${this.bucket}/${objectPath}`, {
      headers: { authorization: `Bearer ${this.key}`, apikey: this.key },
      signal: AbortSignal.timeout(15_000),
    });
    if (res.status === 404 || res.status === 400) return null;
    if (!res.ok) throw new Error(`storage_get_${res.status}`);
    return { data: Buffer.from(await res.arrayBuffer()), contentType: res.headers.get('content-type') ?? 'image/webp' };
  }
}

/**
 * Object paths are generated by uploadAvatar as `<user uuid>/<16 base64url chars>.webp`. Only that
 * exact shape is accepted, which rules out traversal (`..`), separators, drive letters, alternate
 * data streams (`:`), Windows device names (CON, NUL, ...) and trailing dots or spaces.
 */
const OBJECT_PATH = /^([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\/([A-Za-z0-9_-]{16}\.webp)$/;

export class StorageError extends Error {
  constructor(readonly code: 'invalid_object_path' | 'storage_root_unavailable' | 'storage_link_refused') {
    super(code);
    this.name = 'StorageError';
  }
}

/**
 * Production avatar storage on the local disk (WIN-02). The root is fixed by configuration and kept
 * outside the program directory; files are only reachable through the API route, never served as
 * static files. Writes go to a temporary file in the same directory, are flushed, then renamed, so a
 * reader never sees a partial image. Errors are thrown (not swallowed) so callers can log them.
 */
export class FilesystemAvatarStorage implements AvatarStorage {
  readonly mode = 'real' as const;
  readonly backend = 'filesystem' as const;
  constructor(private root: string) {}

  private resolve(objectPath: string) {
    const m = OBJECT_PATH.exec(objectPath);
    if (!m) throw new StorageError('invalid_object_path');
    const dir = path.join(this.root, m[1]);
    const file = path.join(dir, m[2]);
    const rel = path.relative(this.root, file);
    if (rel.startsWith('..') || path.isAbsolute(rel)) throw new StorageError('invalid_object_path');
    return { dir, file, name: m[2] };
  }

  private async assertRoot() {
    const st = await stat(this.root).catch(() => null);
    if (!st?.isDirectory()) throw new StorageError('storage_root_unavailable');
  }

  /** user directories and files are created by this class: a link or junction there was planted */
  private async assertNotLink(target: string, kind: 'dir' | 'file') {
    const st = await lstat(target);
    if (st.isSymbolicLink() || (kind === 'dir' ? !st.isDirectory() : !st.isFile())) throw new StorageError('storage_link_refused');
  }

  async put(objectPath: string, data: Buffer) {
    const { dir, file, name } = this.resolve(objectPath);
    await this.assertRoot();
    await mkdir(dir).catch((e: NodeJS.ErrnoException) => { if (e.code !== 'EEXIST') throw e; });
    await this.assertNotLink(dir, 'dir');
    const tmp = path.join(dir, `.${name}.${randomBytes(6).toString('hex')}.tmp`);
    const fh = await open(tmp, 'wx', 0o600);
    try {
      await fh.writeFile(data);
      await fh.sync();
      await fh.close();
      await rename(tmp, file);
    } catch (e) {
      await fh.close().catch(() => undefined);
      await rm(tmp, { force: true }).catch(() => undefined);
      throw e;
    }
  }

  async get(objectPath: string) {
    const { dir, file } = this.resolve(objectPath);
    await this.assertRoot();
    try {
      await this.assertNotLink(dir, 'dir');
      await this.assertNotLink(file, 'file');
      return { data: await readFile(file), contentType: 'image/webp' };
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw e;
    }
  }
}

/** Test double: development/test storage under .data/ (git-ignored). Refused in staging/production. */
export class LocalAvatarStorage implements AvatarStorage {
  readonly mode = 'fake' as const;
  readonly backend = 'fake' as const;
  constructor(private root = path.join(process.cwd(), '.data', 'avatars')) {}
  async put(objectPath: string, data: Buffer) {
    const file = path.join(this.root, objectPath);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
  }
  async get(objectPath: string) {
    try {
      return { data: await readFile(path.join(this.root, objectPath)), contentType: 'image/webp' };
    } catch {
      return null;
    }
  }
}

const g = globalThis as unknown as { __csbStorage?: AvatarStorage };

export function getAvatarStorage(): AvatarStorage {
  if (!g.__csbStorage) {
    const cfg = getConfig();
    // getConfig has already refused a backend without its settings
    if (cfg.storageBackend === 'filesystem' && cfg.avatarStorageDir) g.__csbStorage = new FilesystemAvatarStorage(cfg.avatarStorageDir);
    else if (cfg.storageBackend === 'supabase' && cfg.supabaseUrl && cfg.supabaseServiceRoleKey) {
      g.__csbStorage = new SupabaseAvatarStorage(cfg.supabaseUrl, cfg.supabaseServiceRoleKey, cfg.supabaseAvatarBucket);
    } else g.__csbStorage = new LocalAvatarStorage();
  }
  return g.__csbStorage;
}

export function setAvatarStorage(s: AvatarStorage | undefined) {
  g.__csbStorage = s;
}
