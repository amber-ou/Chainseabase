import { test, expect } from '@playwright/test';
import { createRequire } from 'node:module';
const axePath = createRequire(import.meta.url).resolve('axe-core/axe.min.js');

test('all ten primitives render and retain accessible interaction', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('產品名稱', { exact: true }).fill('我的產品');
  await expect(page.getByLabel('產品名稱', { exact: true })).toHaveValue('我的產品');
  await expect(page.getByRole('cell', { name: '測試產品' })).toBeVisible();
  await page.getByRole('button', { name: '操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '選取產品' }).click();
  await expect(page.getByText('已選取', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '詳細', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toHaveText('詳細內容');
  await page.getByRole('tab', { name: '詳細', exact: true }).press('ArrowLeft');
  await expect(page.getByRole('cell', { name: '測試產品' })).toBeVisible();
  await page.getByRole('combobox', { name: '選擇產品' }).click();
  await page.getByRole('option', { name: '產品 B' }).click();
  await expect(page.getByRole('combobox')).toHaveText('產品 B');
  await page.getByRole('button', { name: '編輯', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '編輯產品' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByLabel('新名稱')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(dialog).toBeHidden();
  await expect(page.getByRole('button', { name: '編輯', exact: true })).toBeFocused();
  await page.getByRole('button', { name: '說明', exact: true }).hover();
  await expect(page.getByRole('tooltip')).toHaveText('操作說明');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toBeHidden();
  await expect(page.getByRole('button', { name: '編輯', exact: true })).toHaveCSS('background-color', 'rgb(20, 20, 20)');
  await expect(page.getByLabel('產品名稱', { exact: true })).toHaveCSS('border-radius', '6px');
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.addScriptTag({ path: axePath });
  const violations = await page.evaluate(async () => (await (window as any).axe.run(document, { runOnly: ['wcag2a', 'wcag2aa', 'wcag21aa'] })).violations);
  expect(violations).toEqual([]);
  expect(errors).toEqual([]);
  await page.screenshot({ path: test.info().outputPath('components.png'), fullPage: true });
});
